static int exit_callback(int a, int b, void *c) {
    (void)a; (void)b; (void)c;
    sceKernelExitGame();
    return 0;
}
static int callback_thread(SceSize args, void *argp) {
    (void)args; (void)argp;
    int cb = sceKernelCreateCallback("Exit Callback", exit_callback, NULL);
    sceKernelRegisterExitCallback(cb);
    sceKernelSleepThreadCB();
    return 0;
}
static void setup_callbacks(void) {
    int t = sceKernelCreateThread("update_thread", callback_thread, 0x11, 0xFA0, 0, 0);
    if (t >= 0) sceKernelStartThread(t, 0, 0);
}

/* ---------- GU setup ---------- */
static void *fbp0 = NULL;
static void *fbp1 = NULL;
static void *zbp  = NULL;

void plat_init(void) {
    setup_callbacks();
    sceCtrlSetSamplingCycle(0);
    sceCtrlSetSamplingMode(PSP_CTRL_MODE_DIGITAL);

    fbp0 = (void*)(0x04000000);                 /* VRAM */
    fbp1 = (void*)((uintptr_t)fbp0 + 512*272*4);
    zbp  = (void*)((uintptr_t)fbp1 + 512*272*4);

    sceGuInit();
    sceGuStart(GU_DIRECT, list);
    sceGuDrawBuffer(GU_PSM_8888, fbp0, BUF_WIDTH);
    sceGuDispBuffer(SCREEN_W, SCREEN_H, fbp1, BUF_WIDTH);
    sceGuDepthBuffer(zbp, BUF_WIDTH);
    sceGuOffset(2048 - (SCREEN_W/2), 2048 - (SCREEN_H/2));
    sceGuViewport(2048, 2048, SCREEN_W, SCREEN_H);
    sceGuDepthRange(65535, 0);
    sceGuScissor(0, 0, SCREEN_W, SCREEN_H);
    sceGuEnable(GU_SCISSOR_TEST);
    sceGuDisable(GU_DEPTH_TEST);
    sceGuEnable(GU_BLEND);
    sceGuBlendFunc(GU_ADD, GU_SRC_ALPHA, GU_ONE_MINUS_SRC_ALPHA, 0, 0);
    sceGuDisable(GU_TEXTURE_2D);
    sceGuFinish();
    sceGuSync(0, 0);
    sceDisplayWaitVblankStart();
    sceGuDisplay(GU_TRUE);
}

void plat_shutdown(void) {
    sceGuTerm();
}

void plat_begin_frame(void) {
    sceGuStart(GU_DIRECT, list);
    sceGuClearColor(C_BG);
    sceGuClear(GU_COLOR_BUFFER_BIT);
}

void plat_end_frame(void) {
    sceGuFinish();
    sceGuSync(0, 0);
    sceDisplayWaitVblankStart();
    sceGuSwapBuffers();
}

void plat_clear(uint32_t color) {
    sceGuClearColor(color);
    sceGuClear(GU_COLOR_BUFFER_BIT);
}

/* Simple coloured rectangle using GU */
typedef struct {
    unsigned int color;
    short x, y, z;
} VertC;

void plat_rect(int x, int y, int w, int h, uint32_t color) {
    if (w <= 0 || h <= 0) return;
    VertC *v = (VertC*)sceGuGetMemory(2 * sizeof(VertC));
    v[0].color = color; v[0].x = (short)x;     v[0].y = (short)y;     v[0].z = 0;
    v[1].color = color; v[1].x = (short)(x+w); v[1].y = (short)(y+h); v[1].z = 0;
    sceGuDisable(GU_TEXTURE_2D);
    sceGuDrawArray(GU_SPRITES, GU_COLOR_8888 | GU_VERTEX_16BIT | GU_TRANSFORM_2D, 2, 0, v);
}

void plat_rect_border(int x, int y, int w, int h, uint32_t color, int t) {
    plat_rect(x, y, w, t, color);                 /* top */
    plat_rect(x, y+h-t, w, t, color);             /* bottom */
    plat_rect(x, y, t, h, color);                 /* left */
    plat_rect(x+w-t, y, t, h, color);             /* right */
}

/* Tiny software text (8x8) */
void plat_text(int x, int y, const char *s, uint32_t color) {
    if (!s) return;
    for (; *s; s++, x += 8) {
        unsigned char c = (unsigned char)*s;
        if (c < 32 || c > 127) c = '?';
        const unsigned char *glyph = font8x8[c - 32];
        for (int row = 0; row < 8; row++) {
            unsigned char bits = glyph[row];
            for (int col = 0; col < 8; col++) {
                if (bits & (1 << col)) {
                    plat_rect(x + col, y + row, 1, 1, color);
                }
            }
        }
    }
}

void plat_text_centered(int x, int y, int w, const char *s, uint32_t color) {
    int len = 0;
    for (const char *p = s; *p; p++) len++;
    int tx = x + (w - len * 8) / 2;
    if (tx < x) tx = x;
    plat_text(tx, y, s, color);
}

/* Placeholder sprite: coloured square with dex number.
   Later this will sample from a 32x32 atlas texture. */
void plat_sprite(int x, int y, int national_dex) {
    if (national_dex <= 0) {
        plat_rect(x, y, 32, 32, C_SLOT_EMPTY);
        return;
    }
    /* Simple hash colour so different species look distinct */
    uint32_t h = (uint32_t)national_dex * 2654435761u;
    uint32_t r = 80 + (h & 0x7F);
    uint32_t g = 80 + ((h >> 8) & 0x7F);
    uint32_t b = 80 + ((h >> 16) & 0x7F);
    uint32_t col = 0xFF000000 | (b << 16) | (g << 8) | r;
    plat_rect(x, y, 32, 32, col);

    /* Small number in corner */
    char buf[8];
    snprintf(buf, sizeof buf, "%d", national_dex);
    plat_text(x + 1, y + 1, buf, C_TEXT);
}

/* ---------- input ---------- */
static const struct { unsigned mask; Btn btn; int repeat; } MAP[] = {
    { PSP_CTRL_UP, B_UP, 1 },         { PSP_CTRL_DOWN, B_DOWN, 1 },
    { PSP_CTRL_LEFT, B_LEFT, 0 },     { PSP_CTRL_RIGHT, B_RIGHT, 0 },
    { PSP_CTRL_CROSS, B_CROSS, 0 },   { PSP_CTRL_CIRCLE, B_CIRCLE, 0 },
    { PSP_CTRL_TRIANGLE, B_TRIANGLE, 0 }, { PSP_CTRL_SQUARE, B_SQUARE, 0 },
    { PSP_CTRL_LTRIGGER, B_L, 1 },    { PSP_CTRL_RTRIGGER, B_R, 1 },
    { PSP_CTRL_START, B_START, 0 },
};

Btn plat_wait_button(void) {
    static unsigned prev = 0xFFFFFFFF;
    static int held = 0;
    SceCtrlData pad;
    const unsigned n = sizeof MAP / sizeof MAP[0];
    for (;;) {
        sceDisplayWaitVblankStart();
        sceCtrlPeekBufferPositive(&pad, 1);
        unsigned now = pad.Buttons, fresh = now & ~prev;
        for (unsigned i = 0; i < n; i++)
            if (fresh & MAP[i].mask) { prev = now; held = 0; return MAP[i].btn; }
        int rep = 0;
        for (unsigned i = 0; i < n; i++) {
            if (MAP[i].repeat && (now & MAP[i].mask)) {
                rep = 1;
                if (++held > 18 && (held % 4) == 0) { prev = now; return MAP[i].btn; }
                break;
            }
        }
        if (!rep) held = 0;
        prev = now;
    }
}

/* ---------- filesystem ---------- */
void plat_walk_dir(const char *dir, plat_dir_cb cb, void *ud) {
    SceUID d = sceIoDopen(dir);
    if (d < 0) return;
    SceIoDirent ent;
    memset(&ent, 0, sizeof ent);
    while (sceIoDread(d, &ent) > 0) {
        if (strcmp(ent.d_name, ".") && strcmp(ent.d_name, "..")) {
            if (cb(ent.d_name, FIO_S_ISDIR(ent.d_stat.st_mode) ? 1 : 0,
                   (long)ent.d_stat.st_size, ud)) break;
        }
        memset(&ent, 0, sizeof ent);
    }
    sceIoDclose(d);
}

const char *plat_scan_root(void) { return "ms0:/"; }
const char *plat_storage_path(void) { return g_storage; }
void plat_exit(void) { sceKernelExitGame(); }

int main(int argc, char *argv[]) {
    /* keep PKSTORAGE.bin next to the EBOOT */
    if (argc > 0 && argv[0]) {
        char *slash = strrchr(argv[0], '/');
        if (slash) {
            size_t n = (size_t)(slash - argv[0]) + 1;
            if (n + 16 < sizeof g_storage) {
                memcpy(g_storage, argv[0], n);
                strcpy(g_storage + n, "PKSTORAGE.bin");
            }
        }
    }
    plat_init();
    app_run();
    plat_shutdown();
    sceKernelExitGame();
    return 0;
}
